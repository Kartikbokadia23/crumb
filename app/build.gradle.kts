fun quotedConfig(name: String, default: String = ""): String {
    val localProperties = Properties()
    val localPropertiesFile = rootProject.file("local.properties")
    if (localPropertiesFile.exists()) {
        localPropertiesFile.inputStream().use { input -> localProperties.load(input) }
    }
    val fromLocalProperties = localProperties.getProperty(name)
    val fromProperty = providers.gradleProperty(name).orNull
    val fromEnv = providers.environmentVariable(name).orNull
    return "\"${(fromProperty ?: fromEnv ?: fromLocalProperties ?: default).replace("\\", "\\\\").replace("\"", "\\\"")}\""
}
